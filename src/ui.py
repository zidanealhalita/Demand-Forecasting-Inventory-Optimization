"""Shared Streamlit UI: sidebar filters (shared by all pages), page header and the mandatory footer."""
from __future__ import annotations

from dataclasses import dataclass

import pandas as pd
import streamlit as st

from .viz import FOOTER_TEXT

K_CAT, K_SKU, K_REG, K_DATES = "flt_cat", "flt_sku", "flt_reg", "flt_dates"


@dataclass
class Filters:
    """Current sidebar selection. Empty lists mean 'all'."""

    categories: list[str]
    skus: list[str]
    regions: list[str]
    date_from: pd.Timestamp
    date_to: pd.Timestamp

    def label(self) -> str:
        """Short text describing the active filter (for captions)."""
        c = ", ".join(self.categories) if self.categories else "all categories"
        s = ", ".join(self.skus) if self.skus else "all SKUs"
        r = ", ".join(self.regions) if self.regions else "all regions"
        return f"{c} | {s} | {r} | {self.date_from:%d %b %Y} - {self.date_to:%d %b %Y}"


def _options(panel: pd.DataFrame) -> tuple[list[str], list[str], list[str]]:
    cats = sorted(panel["category"].unique())
    sku_opts = sorted(panel.loc[panel["category"].isin(st.session_state.get(K_CAT) or cats), "sku_id"].unique())
    regs = sorted(panel["region"].unique())
    return cats, sku_opts, regs


def render_sidebar(panel: pd.DataFrame) -> None:
    """Draw the shared filters. Called once from ``app.py`` before the page runs."""
    cats, sku_opts, regs = _options(panel)
    st.session_state[K_SKU] = [s for s in st.session_state.get(K_SKU, []) if s in sku_opts]
    st.sidebar.markdown("### Filters")
    st.sidebar.caption("Leave a box empty to include everything. Applies to the Overview, Demand Patterns, Supply Risk and Recommendations pages.")
    st.sidebar.multiselect("Category", cats, key=K_CAT, placeholder="All categories")
    st.sidebar.multiselect("SKU", sku_opts, key=K_SKU, placeholder="All SKUs")
    st.sidebar.multiselect("Region", regs, key=K_REG, placeholder="All regions")
    lo, hi = panel["date"].min().date(), panel["date"].max().date()
    st.sidebar.date_input("Date range", value=(lo, hi), min_value=lo, max_value=hi, key=K_DATES)
    st.sidebar.divider()
    st.sidebar.caption("Synthetic data for portfolio purposes.")


def get_filters(panel: pd.DataFrame) -> Filters:
    """Read the current filters from session state (defaults = everything), so pages also run stand-alone."""
    lo, hi = panel["date"].min(), panel["date"].max()
    d = st.session_state.get(K_DATES, (lo.date(), hi.date()))
    if isinstance(d, (list, tuple)) and len(d) == 2:
        d0, d1 = pd.Timestamp(d[0]), pd.Timestamp(d[1])
    else:
        d0, d1 = lo, hi
    return Filters(
        categories=list(st.session_state.get(K_CAT, [])),
        skus=list(st.session_state.get(K_SKU, [])),
        regions=list(st.session_state.get(K_REG, [])),
        date_from=max(d0, lo),
        date_to=min(d1, hi),
    )


def apply_filters(df: pd.DataFrame, f: Filters, date_col: str | None = "date", dates: bool = True) -> pd.DataFrame:
    """Filter a frame having ``category``, ``sku_id`` and ``region`` columns (and optionally dates)."""
    m = pd.Series(True, index=df.index)
    if f.categories and "category" in df:
        m &= df["category"].isin(f.categories)
    if f.skus and "sku_id" in df:
        m &= df["sku_id"].isin(f.skus)
    if f.regions and "region" in df:
        m &= df["region"].isin(f.regions)
    if dates and date_col and date_col in df:
        m &= (df[date_col] >= f.date_from) & (df[date_col] <= f.date_to)
    return df[m]


def series_selector(panel: pd.DataFrame, f: Filters, key: str) -> tuple[str, str]:
    """Pick one SKU x region (defaults to the first item of the sidebar selection)."""
    skus = sorted(panel["sku_id"].unique())
    regs = sorted(panel["region"].unique())
    d_sku = next((s for s in f.skus if s in skus), "MLK-UHT200")
    d_reg = next((r for r in f.regions if r in regs), "Jawa Timur")
    c1, c2 = st.columns(2)
    names = panel.drop_duplicates("sku_id").set_index("sku_id")["sku_name"].to_dict()
    sku = c1.selectbox("SKU", skus, index=skus.index(d_sku), key=f"{key}_sku", format_func=lambda s: f"{s} - {names[s]}")
    reg = c2.selectbox("Region", regs, index=regs.index(d_reg), key=f"{key}_reg")
    return sku, reg


def page_header(title: str, decision: str) -> None:
    """Title plus the business decision the page supports."""
    st.title(title)
    st.info(f"**Decision supported:** {decision}", icon=":material/target:")


def footer() -> None:
    """Footer shown on every page."""
    st.divider()
    st.caption(f"{FOOTER_TEXT} Generated by a simulation script; SKU names are generic, no real brands.")
